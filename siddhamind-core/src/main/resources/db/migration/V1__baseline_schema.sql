    CONSTRAINT fk_dxs_formulation FOREIGN KEY (form_id)
        REFERENCES formulations (form_id) ON DELETE CASCADE,
    CONSTRAINT uq_dxs_session_form UNIQUE (session_id, form_id)
);

-- ---------- corpus ----------
CREATE TABLE source_documents (
    doc_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug            VARCHAR(100) NOT NULL,
    title           VARCHAR(300) NOT NULL,
    author          VARCHAR(300),
    book_code       VARCHAR(50),
    language        VARCHAR(30),
    total_pages     INTEGER,
    file_path       VARCHAR(500),
    uploaded_by     BIGINT,
    uploaded_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    indexed         BOOLEAN      NOT NULL DEFAULT FALSE,
    chunk_count     INTEGER      NOT NULL DEFAULT 0,
    ingest_status   VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    ingest_error    TEXT,
    skipped_pages   INTEGER      NOT NULL DEFAULT 0,
    last_indexed_at TIMESTAMPTZ,
    CONSTRAINT pk_source_documents PRIMARY KEY (doc_id),
    CONSTRAINT uq_source_documents_slug UNIQUE (slug),
    CONSTRAINT fk_docs_uploader FOREIGN KEY (uploaded_by)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_docs_ingest_status
        CHECK (ingest_status IN ('PENDING', 'RUNNING', 'COMPLETE', 'FAILED'))
);

-- ---------- chunks + embeddings (written by siddhamind-ai) ----------
--
-- Dimension 1024 matches BAAI/bge-m3, whose dense vector is 1024-d.
-- intfloat/multilingual-e5-large is also 1024-d, so either model fits without a
-- migration. Changing to a model of a different width (e.g. all-MiniLM at 384)
-- requires ALTER TABLE and a full re-index - the column width is fixed.
CREATE TABLE doc_chunks (
    chunk_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_document_id BIGINT       NOT NULL,
    book_name          VARCHAR(300),
    page_no            INTEGER,
    verse_no           VARCHAR(30),
    chunk_index        INTEGER      NOT NULL,
    content            TEXT         NOT NULL,
    token_count        INTEGER,
    embedding          vector(1024),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_doc_chunks PRIMARY KEY (chunk_id),
    -- Re-ingesting a document deletes its chunks first; this makes an orphaned
    -- embedding impossible.
    CONSTRAINT fk_chunks_document FOREIGN KEY (source_document_id)
        REFERENCES source_documents (doc_id) ON DELETE CASCADE,
    CONSTRAINT uq_chunks_doc_index UNIQUE (source_document_id, chunk_index)
);

CREATE INDEX ix_chunks_document ON doc_chunks (source_document_id);
CREATE INDEX ix_chunks_book ON doc_chunks (book_name);

-- Full-text search over the chunk body. This is the keyword half of the hybrid
-- retrieval the RAG assistant needs; 'simple' rather than 'english' because the
-- corpus is mostly Tamil and English stemming would mangle transliterations.
CREATE INDEX ix_chunks_content_fts ON doc_chunks
    USING gin (to_tsvector('simple', content));

-- HNSW over cosine distance. Built here on an empty table, which is cheap; on a
-- populated table this would need CONCURRENTLY. pgvector caps HNSW at 2000
-- dimensions, so 1024 is comfortably inside.
CREATE INDEX ix_chunks_embedding_hnsw ON doc_chunks
    USING hnsw (embedding vector_cosine_ops);

-- ---------- chat ----------
CREATE TABLE chat_sessions (
    chat_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    title           VARCHAR(300),
    message_count   INTEGER     NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_message_at TIMESTAMPTZ,
    CONSTRAINT pk_chat_sessions PRIMARY KEY (chat_id),
    CONSTRAINT fk_chat_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE
);
CREATE INDEX ix_chat_user_created ON chat_sessions (user_id, created_at DESC);

CREATE TABLE chat_messages (
    message_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    chat_id             BIGINT      NOT NULL,
    sender              VARCHAR(20) NOT NULL,
    message             TEXT        NOT NULL,
    not_found_in_corpus BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_chat_messages PRIMARY KEY (message_id),
    CONSTRAINT fk_msg_chat FOREIGN KEY (chat_id)
        REFERENCES chat_sessions (chat_id) ON DELETE CASCADE,
    CONSTRAINT ck_msg_sender CHECK (sender IN ('USER', 'ASSISTANT'))
);
CREATE INDEX ix_msg_chat_created ON chat_messages (chat_id, created_at);

CREATE TABLE chat_message_citations (
    citation_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_id         BIGINT  NOT NULL,
    source_document_id BIGINT,
    chunk_id           BIGINT,
    book_name          VARCHAR(300),
    page_no            INTEGER,
    verse_no           VARCHAR(30),
    chunk_index        INTEGER,
    passage_no         INTEGER,
    snippet            TEXT,
    score              DOUBLE PRECISION,
    CONSTRAINT pk_chat_message_citations PRIMARY KEY (citation_id),
    CONSTRAINT fk_cite_message FOREIGN KEY (message_id)
        REFERENCES chat_messages (message_id) ON DELETE CASCADE,
    CONSTRAINT fk_cite_document FOREIGN KEY (source_document_id)
        REFERENCES source_documents (doc_id) ON DELETE SET NULL,
    -- A citation outlives re-ingestion of the chunk it came from; the denormalized
    -- book/page/snippet keep it readable after the chunk row is replaced.
    CONSTRAINT fk_cite_chunk FOREIGN KEY (chunk_id)
        REFERENCES doc_chunks (chunk_id) ON DELETE SET NULL
);
CREATE INDEX ix_cite_message ON chat_message_citations (message_id);

-- ---------- activity + notifications ----------
CREATE TABLE activity_logs (
    log_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id    BIGINT,
    action     VARCHAR(50) NOT NULL,
    details    VARCHAR(500),
