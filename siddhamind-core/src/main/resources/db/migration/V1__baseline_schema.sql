CREATE TABLE diagnosis_suggestions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT  NOT NULL,
    form_id    BIGINT  NOT NULL,
    ordinal    INTEGER NOT NULL,
    CONSTRAINT pk_diagnosis_suggestions PRIMARY KEY (id),
