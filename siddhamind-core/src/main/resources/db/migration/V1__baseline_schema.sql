-- ============================================================
--  SiddhaMind AI - baseline schema (Supabase Postgres)
--
--  Every relationship the original MySQL design left implicit is a real FOREIGN KEY
--  here. The relational version stored bare Long columns (form_id, ingredient_id,
--  drug_id) with no constraint, so a deleted ingredient left formulations pointing
--  at nothing and the safety checker would silently under-report.
--
--  ON DELETE rules are deliberate, not defaults:
--    RESTRICT  - reference data another table depends on clinically
--    CASCADE   - rows that have no meaning without their parent
--    SET NULL  - audit rows that must outlive the actor
-- ============================================================

CREATE EXTENSION IF NOT EXISTS vector;

-- ---------- roles ----------
CREATE TABLE roles (
    role_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_name   VARCHAR(30)  NOT NULL,
    description VARCHAR(200),
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_role_name UNIQUE (role_name)
);

-- ---------- users ----------
CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR(120) NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    role_id       BIGINT       NOT NULL,
    reg_number    VARCHAR(50),
    institution   VARCHAR(200),
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    last_login    TIMESTAMPTZ,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    -- Postgres gives the unique constraint the relational version relied on the
    -- application to enforce, so concurrent signups cannot both win.
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id)
        REFERENCES roles (role_id) ON DELETE RESTRICT
);
CREATE INDEX ix_users_role ON users (role_id);

-- ---------- ingredients ----------
CREATE TABLE ingredients (
    ingredient_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug            VARCHAR(100) NOT NULL,
    name_tamil      VARCHAR(100),
    name_english    VARCHAR(100),
    scientific_name VARCHAR(200),
    source_type     VARCHAR(20),
    part_used       VARCHAR(100),
    sutthi_required BOOLEAN      NOT NULL DEFAULT FALSE,
    heavy_metal     BOOLEAN      NOT NULL DEFAULT FALSE,
    element_symbol  VARCHAR(5),
    toxicity_class  VARCHAR(20),
    max_daily_mg    INTEGER,
    notes           TEXT,
    CONSTRAINT pk_ingredients PRIMARY KEY (ingredient_id),
    CONSTRAINT uq_ingredients_slug UNIQUE (slug)
);
CREATE INDEX ix_ingredients_heavy_metal ON ingredients (heavy_metal) WHERE heavy_metal;

-- ---------- diseases ----------
CREATE TABLE diseases (
    disease_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug              VARCHAR(100) NOT NULL,
    noi_tamil         VARCHAR(100),
    noi_english       VARCHAR(100),
    modern_equivalent VARCHAR(200),
    mukkutram_type    VARCHAR(20),
    description       TEXT,
    CONSTRAINT pk_diseases PRIMARY KEY (disease_id),
    CONSTRAINT uq_diseases_slug UNIQUE (slug)
);
CREATE INDEX ix_diseases_mukkutram ON diseases (mukkutram_type);

-- ---------- allopathic drugs ----------
CREATE TABLE allopathic_drugs (
    drug_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug            VARCHAR(100) NOT NULL,
    drug_name       VARCHAR(100) NOT NULL,
    -- Postgres could do this with LOWER() or citext, but a stored column keeps the
    -- lookup on a plain btree index and matches what the safety form sends.
    drug_name_lower VARCHAR(100) NOT NULL,
    drug_class      VARCHAR(100),
    common_brand    VARCHAR(100),
    notes           TEXT,
    CONSTRAINT pk_allopathic_drugs PRIMARY KEY (drug_id),
    CONSTRAINT uq_allopathic_drugs_slug UNIQUE (slug)
);
CREATE INDEX ix_drugs_name_lower ON allopathic_drugs (drug_name_lower);

-- ---------- formulations ----------
CREATE TABLE formulations (
    form_id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slug                 VARCHAR(100) NOT NULL,
    name_tamil           VARCHAR(200),
    name_english         VARCHAR(200),
    sfi_code             VARCHAR(30),
    dosage_form          VARCHAR(50),
    source_book          VARCHAR(200),
    page_no              INTEGER,
    verse_no             VARCHAR(30),
    preparation_method   TEXT,
    dose                 VARCHAR(200),
    anupanam             VARCHAR(200),
    shelf_life           VARCHAR(50),
    contains_heavy_metal BOOLEAN      NOT NULL DEFAULT FALSE,
    safety_class         VARCHAR(10),
    CONSTRAINT pk_formulations PRIMARY KEY (form_id),
    CONSTRAINT uq_formulations_slug UNIQUE (slug)
);
CREATE INDEX ix_formulations_heavy_metal ON formulations (contains_heavy_metal) WHERE contains_heavy_metal;
-- Backs the formulary search, which the Firestore version had to do in memory.
CREATE INDEX ix_formulations_name_english_lower ON formulations (LOWER(name_english));

-- ---------- formulation composition ----------
CREATE TABLE formulation_ingredients (
    fi_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    form_id       BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity      VARCHAR(200),
    sutthi_note   VARCHAR(300),
    CONSTRAINT pk_formulation_ingredients PRIMARY KEY (fi_id),
    -- Deleting a formulation removes its composition rows; they mean nothing alone.
    CONSTRAINT fk_fi_formulation FOREIGN KEY (form_id)
        REFERENCES formulations (form_id) ON DELETE CASCADE,
    -- An ingredient in use cannot be deleted. This is the constraint whose absence
    -- would let a heavy metal vanish from a safety check.
    CONSTRAINT fk_fi_ingredient FOREIGN KEY (ingredient_id)
        REFERENCES ingredients (ingredient_id) ON DELETE RESTRICT,
    CONSTRAINT uq_fi_form_ingredient UNIQUE (form_id, ingredient_id)
);
CREATE INDEX ix_fi_ingredient ON formulation_ingredients (ingredient_id);

CREATE TABLE formulation_diseases (
    fd_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    form_id       BIGINT NOT NULL,
    disease_id    BIGINT NOT NULL,
    evidence_note VARCHAR(300),
    CONSTRAINT pk_formulation_diseases PRIMARY KEY (fd_id),
    CONSTRAINT fk_fd_formulation FOREIGN KEY (form_id)
        REFERENCES formulations (form_id) ON DELETE CASCADE,
    CONSTRAINT fk_fd_disease FOREIGN KEY (disease_id)
        REFERENCES diseases (disease_id) ON DELETE RESTRICT,
    CONSTRAINT uq_fd_form_disease UNIQUE (form_id, disease_id)
);
CREATE INDEX ix_fd_disease ON formulation_diseases (disease_id);

-- ---------- interactions ----------
CREATE TABLE interactions (
    interaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ingredient_id  BIGINT      NOT NULL,
    drug_id        BIGINT      NOT NULL,
    severity       VARCHAR(20) NOT NULL,
    mechanism      TEXT,
    advice         TEXT,
    CONSTRAINT pk_interactions PRIMARY KEY (interaction_id),
    CONSTRAINT fk_interactions_ingredient FOREIGN KEY (ingredient_id)
        REFERENCES ingredients (ingredient_id) ON DELETE CASCADE,
    CONSTRAINT fk_interactions_drug FOREIGN KEY (drug_id)
        REFERENCES allopathic_drugs (drug_id) ON DELETE CASCADE,
    -- Carries over the guarantee the Firestore composite document ID gave: one row
    -- per pair. The original MySQL schema allowed duplicates.
    CONSTRAINT uq_interactions_pair UNIQUE (ingredient_id, drug_id),
    CONSTRAINT ck_interactions_severity CHECK (severity IN ('MAJOR', 'MODERATE', 'MINOR'))
);
CREATE INDEX ix_interactions_drug ON interactions (drug_id);

-- ---------- contraindications ----------
CREATE TABLE contraindications (
    contra_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    form_id        BIGINT       NOT NULL,
    condition_name VARCHAR(100) NOT NULL,
    severity       VARCHAR(20)  NOT NULL,
    note           TEXT,
    CONSTRAINT pk_contraindications PRIMARY KEY (contra_id),
    CONSTRAINT fk_contra_formulation FOREIGN KEY (form_id)
        REFERENCES formulations (form_id) ON DELETE CASCADE,
    CONSTRAINT uq_contra_form_condition UNIQUE (form_id, condition_name),
    CONSTRAINT ck_contra_severity CHECK (severity IN ('MAJOR', 'MODERATE', 'MINOR'))
);

-- ---------- safety checks (audit trail) ----------
CREATE TABLE safety_checks (
    check_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id                    BIGINT,
    form_id                    BIGINT,
    formulation_name           VARCHAR(400),
    drugs_entered              TEXT,
    conditions_entered         TEXT,
    risk_level                 VARCHAR(20) NOT NULL,
    major_count                INTEGER     NOT NULL DEFAULT 0,
    moderate_count             INTEGER     NOT NULL DEFAULT 0,
    minor_count                INTEGER     NOT NULL DEFAULT 0,
    heavy_metal_daily_limit_mg DOUBLE PRECISION NOT NULL DEFAULT 0,
    unmatched_drugs            TEXT,
    ai_explanation             TEXT,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_safety_checks PRIMARY KEY (check_id),
    -- An audit record must survive the deletion of the user or formulation it
    -- refers to; formulation_name is denormalized here for exactly that reason.
    CONSTRAINT fk_safety_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_safety_formulation FOREIGN KEY (form_id)
        REFERENCES formulations (form_id) ON DELETE SET NULL,
    CONSTRAINT ck_safety_risk CHECK (risk_level IN ('HIGH', 'MODERATE', 'LOW'))
);
CREATE INDEX ix_safety_user_created ON safety_checks (user_id, created_at DESC);
CREATE INDEX ix_safety_created ON safety_checks (created_at DESC);

-- Was a nested findings[] array in Firestore. A child table here so the audit row
-- still shows exactly what the practitioner was told, even after a rule is edited.
CREATE TABLE safety_check_findings (
    finding_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    check_id   BIGINT      NOT NULL,
    ordinal    INTEGER     NOT NULL,
    subject    VARCHAR(400),
    type       VARCHAR(40),
    severity   VARCHAR(20) NOT NULL,
    detail     TEXT,
    advice     TEXT,
    CONSTRAINT pk_safety_check_findings PRIMARY KEY (finding_id),
    CONSTRAINT fk_finding_check FOREIGN KEY (check_id)
        REFERENCES safety_checks (check_id) ON DELETE CASCADE
);
CREATE INDEX ix_findings_check ON safety_check_findings (check_id);

